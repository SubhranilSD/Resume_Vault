-- ResumeVault | PostgreSQL 14+
-- Normalized relational schema (3NF). Run in pgAdmin 4 Query Tool.
-- First create a PostgreSQL database named resume_vault, then run this file in it.

CREATE TABLE IF NOT EXISTS candidates (
  candidate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  phone VARCHAR(30),
  location VARCHAR(120) NOT NULL DEFAULT '',
  linkedin_url VARCHAR(255) DEFAULT '',
  github_url VARCHAR(255) DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_candidate_name ON candidates(full_name);
CREATE INDEX IF NOT EXISTS idx_candidate_location ON candidates(location);

CREATE TABLE IF NOT EXISTS resumes (
  resume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id BIGINT NOT NULL REFERENCES candidates(candidate_id) ON DELETE CASCADE,
  current_title VARCHAR(140) NOT NULL,
  summary TEXT,
  experience_years NUMERIC(4,1) NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
  source VARCHAR(60) NOT NULL DEFAULT 'Direct upload',
  status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','In review','Archived')),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_resume_status_updated ON resumes(status, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_resume_title ON resumes(current_title);
CREATE INDEX IF NOT EXISTS idx_resume_candidate ON resumes(candidate_id);

CREATE TABLE IF NOT EXISTS skills (
  skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_name VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS resume_skills (
  resume_id BIGINT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  skill_id BIGINT NOT NULL REFERENCES skills(skill_id) ON DELETE CASCADE,
  proficiency VARCHAR(20) NOT NULL DEFAULT 'Intermediate'
    CHECK (proficiency IN ('Beginner','Intermediate','Advanced','Expert')),
  PRIMARY KEY (resume_id, skill_id)
);
CREATE INDEX IF NOT EXISTS idx_rs_skill ON resume_skills(skill_id, resume_id);

CREATE TABLE IF NOT EXISTS work_experience (
  experience_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id BIGINT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  company_name VARCHAR(140) NOT NULL,
  job_title VARCHAR(140) NOT NULL,
  started_on DATE NOT NULL,
  ended_on DATE,
  description TEXT
);
CREATE INDEX IF NOT EXISTS idx_experience_resume_dates ON work_experience(resume_id, started_on DESC);
CREATE TABLE IF NOT EXISTS education (
  education_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id BIGINT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  institution VARCHAR(160) NOT NULL,
  degree VARCHAR(120) NOT NULL,
  field_of_study VARCHAR(120),
  graduation_year SMALLINT CHECK (graduation_year BETWEEN 1901 AND 2155)
);
CREATE INDEX IF NOT EXISTS idx_education_resume ON education(resume_id);

CREATE TABLE IF NOT EXISTS job_openings (
  job_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(140) NOT NULL,
  department VARCHAR(100) NOT NULL,
  location VARCHAR(120),
  status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Paused','Closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_job_status_title ON job_openings(status, title);
CREATE TABLE IF NOT EXISTS applications (
  application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resume_id BIGINT NOT NULL REFERENCES resumes(resume_id) ON DELETE CASCADE,
  job_id BIGINT NOT NULL REFERENCES job_openings(job_id) ON DELETE CASCADE,
  stage VARCHAR(20) NOT NULL DEFAULT 'New'
    CHECK (stage IN ('New','Screening','Interview','Offer','Hired','Rejected')),
  applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_application_resume_job UNIQUE (resume_id, job_id)
);
CREATE INDEX IF NOT EXISTS idx_application_job_stage ON applications(job_id, stage);
CREATE TABLE IF NOT EXISTS audit_logs (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_name VARCHAR(64) NOT NULL,
  record_id BIGINT NOT NULL,
  action VARCHAR(10) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
  changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_table_record_time ON audit_logs(table_name, record_id, changed_at DESC);

CREATE OR REPLACE VIEW v_resume_directory AS
SELECT r.resume_id, c.candidate_id, c.full_name, c.email, c.location,
       r.current_title, r.experience_years, r.status, r.source, r.updated_at,
       COALESCE(string_agg(DISTINCT s.skill_name, ', ' ORDER BY s.skill_name), '') AS skills
FROM resumes r
JOIN candidates c ON c.candidate_id = r.candidate_id
LEFT JOIN resume_skills rs ON rs.resume_id = r.resume_id
LEFT JOIN skills s ON s.skill_id = rs.skill_id
GROUP BY r.resume_id, c.candidate_id, c.full_name, c.email, c.location,
         r.current_title, r.experience_years, r.status, r.source, r.updated_at;
CREATE OR REPLACE VIEW v_skill_demand AS
SELECT s.skill_id, s.skill_name, COUNT(DISTINCT rs.resume_id) AS resume_count
FROM skills s LEFT JOIN resume_skills rs ON rs.skill_id = s.skill_id
GROUP BY s.skill_id, s.skill_name;

CREATE OR REPLACE FUNCTION sp_search_resumes(p_term TEXT, p_status TEXT)
RETURNS SETOF v_resume_directory LANGUAGE SQL STABLE AS $$
  SELECT * FROM v_resume_directory
  WHERE (COALESCE(p_term,'') = '' OR full_name ILIKE '%' || p_term || '%'
         OR current_title ILIKE '%' || p_term || '%' OR skills ILIKE '%' || p_term || '%')
    AND (COALESCE(p_status,'') = '' OR status = p_status)
  ORDER BY updated_at DESC;
$$;

CREATE OR REPLACE FUNCTION log_resume_audit() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF (TG_OP = 'DELETE') THEN
    INSERT INTO audit_logs(table_name, record_id, action)
    VALUES ('resumes', OLD.resume_id, TG_OP);
    RETURN OLD;
  END IF;
  INSERT INTO audit_logs(table_name, record_id, action)
  VALUES ('resumes', NEW.resume_id, TG_OP);
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_resume_insert_audit ON resumes;
CREATE TRIGGER trg_resume_insert_audit AFTER INSERT ON resumes
FOR EACH ROW EXECUTE FUNCTION log_resume_audit();
DROP TRIGGER IF EXISTS trg_resume_update_audit ON resumes;
CREATE TRIGGER trg_resume_update_audit AFTER UPDATE ON resumes
FOR EACH ROW EXECUTE FUNCTION log_resume_audit();
DROP TRIGGER IF EXISTS trg_resume_delete_audit ON resumes;
CREATE TRIGGER trg_resume_delete_audit AFTER DELETE ON resumes
FOR EACH ROW EXECUTE FUNCTION log_resume_audit();

